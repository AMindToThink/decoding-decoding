#!/usr/bin/env python3
"""Build script-generated LaTeX for the compiled tech report.

Reads the authoritative ``summary.json`` files produced by the individual
experiments and emits, under ``results/tables/``:

  * ``paper_macros.tex``      -- one ``\\newcommand`` per inline scalar cited
                                 in the paper's prose.
  * ``tab_*.tex``             -- tabular *bodies* (the ``\\begin{tabular}`` ...
                                 ``\\end{tabular}`` block only) for every
                                 multi-row table imported into the paper.

Nothing here is hand-typed from memory: every number resolves to a field in a
JSON file under ``results/``.  The paper ``\\input``s these outputs; prose
references macros, tables ``\\input`` the bodies.  This is the citation analog
of the ``import-content`` discipline.

Re-run after any experiment is re-run:

    uv run python scripts/build_paper_macros.py
"""
from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
CD = ROOT / "results" / "counter_decode"
TABLES = ROOT / "results" / "tables"
OUT_DIR = TABLES


def load(path: Path) -> Any:
    if not path.is_file():
        raise FileNotFoundError(f"required data source missing: {path}")
    with path.open() as fh:
        return json.load(fh)


# ---------------------------------------------------------------------------
# formatting helpers
# ---------------------------------------------------------------------------
def f(x: float, nd: int = 3) -> str:
    """Plain fixed-point."""
    return f"{x:.{nd}f}"


def sgn(x: float, nd: int = 3) -> str:
    """Signed fixed-point (always shows + or -), matching the reports."""
    return f"{x:+.{nd}f}"


def sci(x: float) -> str:
    """Scientific notation for the ~0 corrected closed-loop errors."""
    return f"{x:.1e}".replace("e-0", "e{-}").replace("e+0", "e{+}")


# ---------------------------------------------------------------------------
# load every authoritative source
# ---------------------------------------------------------------------------
src = {
    "f0": load(CD / "tables" / "F0_summary.json"),
    "f12": load(CD / "tables" / "F1.2_summary.json"),
    "f3": load(CD / "tables" / "F3_summary.json"),
    "svd": load(CD / "tables" / "F1_F2_svd_summary.json"),
    "blacklist": load(TABLES / "blacklist_summary.json"),
    "topk": load(TABLES / "topk_summary_L2048.json"),
    "expb": load(CD / "sliding_filter_mixed" / "summary.json"),
    "expc": load(CD / "entropy_probe" / "summary.json"),
    "expc_swap": load(CD / "entropy_probe" / "swap_summary.json"),
    "bsweep": load(CD / "belief_sweep" / "summary.json"),
    "binv": load(CD / "belief_invariance" / "summary.json"),
}

PROV = (
    "% AUTO-GENERATED by scripts/build_paper_macros.py -- do not edit by hand.\n"
    "% Data sources: results/counter_decode/{tables,sliding_filter_mixed,\n"
    "%   entropy_probe,belief_sweep,belief_invariance}/*.json and\n"
    "%   results/tables/{blacklist,topk}_summary*.json ; plus the\n"
    "%   per-experiment macro files calibration_baseline/macros.tex and\n"
    "%   natural_text/macros.tex (digit-in-name sanitised to a word).\n"
)

# accumulate scalar macros and table bodies
macros: dict[str, str] = {}
bodies: dict[str, str] = {}


def M(name: str, value: str) -> None:
    if name in macros:
        raise ValueError(f"duplicate macro name {name}")
    if not name.isalpha():
        # TeX control-sequence names are letters only; a digit would make
        # \fooBar5 parse as \fooBar followed by literal "5".
        raise ValueError(f"macro name must be letters-only (no digits): {name}")
    macros[name] = value


