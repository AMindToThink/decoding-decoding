# ---------------------------------------------------------------------------
# Ingest the per-experiment macro files generated by the report build scripts
# (Exp A calibration baseline, natural-text filter). These are themselves
# authoritative (script-generated from JSON); we re-emit them into the single
# paper macro file, sanitising any digit in a macro NAME to a word so that TeX
# does not split e.g. \calTestPPLWTT1 into \calTestPPLWTT + "1".
# ---------------------------------------------------------------------------
_DIGIT_WORD = {
    "0": "Zero", "1": "One", "2": "Two", "3": "Three", "4": "Four",
    "5": "Five", "6": "Six", "7": "Seven", "8": "Eight", "9": "Nine",
}
_NEWCMD_RE = re.compile(r"^\\newcommand\{\\([A-Za-z0-9]+)\}\{(.*)\}\s*$")


def sanitize_name(name: str) -> str:
    return "".join(_DIGIT_WORD.get(c, c) for c in name)


def ingest(path: Path) -> int:
    n = 0
    for line in path.read_text().splitlines():
        m = _NEWCMD_RE.match(line)
        if m:
            M(sanitize_name(m.group(1)), m.group(2))
            n += 1
    return n


